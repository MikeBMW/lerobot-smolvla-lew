"""🧩 Feature Registry · 能力特征库 (2026-08-19 老倪, 系统工程模块化设计)

══════ 设计思想 ══════
1. **能力视角** — feature 从「模型能做什么」定义, 不写算法/技术实现。
   每个模型都有能力, 能力清单描述模型的能力边界, 而非实现细节。
2. **数据流形态** — 状态空间只是众多形态中的一种数据流。作业数据流:
   感知 → 决策 → 控制 → 执行。
3. **特征库分层** (参考 LeRobot 生态标准) — 8 大类, 每条能力可**复用/增加/组合**:
   - 复用: 能力独立定义, 多模型共用
   - 增加: 第三方模型带新能力 → 注册新能力条目
   - 组合: 模型 = 能力清单 (Manifest), 按需勾选
4. **能力定义完整要素** (老倪要求, 非关键词):
   - explain  解释说明: 能力是什么/怎么工作/解决什么问题 (完整段落)
   - iface    接口定义: 接口用途/输入/输出/对接方式 (完整定义)
   - io_in    输入信号: 信号清单 (名称/类型/说明)
   - io_out   输出信号: 信号清单 (名称/类型/说明)
   - scene    使用场景
   - eng      工程落点 (内部实现定位)
"""
